import { chromium } from 'playwright-core';
import { createGrid, storeProjectEnvelope } from '@pinbean/bead-core';
import { getSupplierPalette } from '@pinbean/palette-data';
import assert from 'node:assert/strict';
const full = getSupplierPalette('MARD');
const palette = getSupplierPalette('MARD', full.colors.slice(0,3).map(c => c.id));
const initialCells = Array.from({length:100}, (_, index) => index % 2 + 1);
const project = { id: 'pencil-smoke', name: 'Pencil smoke', schemaVersion: 1, createdAt: 10, updatedAt: 20, grid: createGrid(10,10,initialCells), paletteId: palette.id, paletteVersion: palette.version, paletteTable: ['',palette.colors[0].id,palette.colors[1].id] };
const fixture = JSON.stringify(storeProjectEnvelope(project,'MARD',palette));
const browser = await chromium.launch({ channel: 'chrome', headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
try {
  const page = await browser.newPage({viewport:{width:1194,height:834},hasTouch:true});
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(process.env.PINBEAN_WEB_URL || 'http://localhost:3015');
  await page.evaluate(data=>localStorage.setItem('pinbean_web_project_v2',data),fixture);
  await page.reload();
  const grid = () => page.evaluate(() => JSON.parse(localStorage.getItem('pinbean_web_project_v2')).project.grid.cells);
  const undoExclusion=page.getByRole('button',{name:'撤销排除',exact:true});
  assert.equal(await undoExclusion.isDisabled(),true);
  await page.locator('.pinbean-color-list li').first().click();
  assert.equal(new Set(await grid()).size,1);
  assert.equal(await undoExclusion.isEnabled(),true);
  await undoExclusion.click();
  assert.deepEqual(await grid(),initialCells);
  assert.equal(await undoExclusion.isDisabled(),true);
  await page.getByRole('button',{name:'校对细节',exact:true}).click();
  await page.getByRole('button',{name:'重做',exact:true}).click();
  assert.equal(new Set(await grid()).size,1);
  assert.equal(await undoExclusion.isEnabled(),true);
  await undoExclusion.click();
  assert.deepEqual(await grid(),initialCells);
  await page.getByRole('button',{name:'校对细节',exact:true}).click();
  await page.getByRole('button', {name:'橡皮擦',exact:true}).click();
  const canvas = page.locator('.pinbean-canvas-stage canvas');
  await canvas.scrollIntoViewIfNeeded();
  const cdp = await page.context().newCDPSession(page);
  const point = async (col,row) => { const b=await canvas.boundingBox(); return { x:b.x+(col+0.5)*b.width/10,y:b.y+(row+0.5)*b.height/10 }; };
  const pixel = (col,row) => canvas.evaluate((node,{col,row}) => {
    const context=node.getContext('2d');
    return [...context.getImageData((col+0.5)*node.width/10,(row+0.5)*node.height/10,1,1).data];
  },{col,row});
  const pen = async (type,p) => cdp.send('Input.dispatchMouseEvent',{type,...p,button:type==='mouseMoved'?'none':'left',buttons:type==='mouseReleased'?0:1,pointerType:'pen',clickCount:1});
  const firstPixelBefore=await pixel(0,0); const secondPixelBefore=await pixel(1,0);
  const secondSwatch=page.getByTitle(`${palette.colors[1].code} (${palette.colors[1].hex})`,{exact:true});
  const swatchBox=await secondSwatch.boundingBox(); const swatchPoint={x:swatchBox.x+swatchBox.width/2,y:swatchBox.y+swatchBox.height/2,id:30};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[swatchPoint]});
  await page.waitForTimeout(80);
  const firstPixelHeld=await pixel(0,0); const secondPixelHeld=await pixel(1,0);
  assert.ok(firstPixelHeld[0] < firstPixelBefore[0] || firstPixelHeld[1] < firstPixelBefore[1] || firstPixelHeld[2] < firstPixelBefore[2]);
  assert.deepEqual(secondPixelHeld,secondPixelBefore);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.waitForTimeout(80);
  assert.deepEqual(await pixel(0,0),firstPixelBefore);
  const originalBox=await canvas.boundingBox();
  await page.getByRole('button',{name:'放大图纸',exact:true}).click();
  await page.waitForTimeout(80);
  const zoomedBox=await canvas.boundingBox();
  assert.ok(Math.abs(zoomedBox.width/originalBox.width-1.25)<0.02);
  await page.getByRole('button',{name:'重置图纸视图',exact:true}).click();
  await page.waitForTimeout(80);
  assert.ok(Math.abs((await canvas.boundingBox()).width-originalBox.width)<2);
  await page.getByTitle(`${palette.colors[0].code} (${palette.colors[0].hex})`,{exact:true}).click();
  await page.getByRole('button',{name:'区域填充',exact:true}).click();
  const fillPrompt=page.getByText('区域填充：点击刚才擦除或需要换色的连续区域',{exact:true});
  assert.equal(await fillPrompt.evaluate(node=>getComputedStyle(node).color),'rgb(255, 255, 255)');
  await page.getByRole('button',{name:'区域填充',exact:true}).click();
  await page.getByRole('button', {name:'橡皮擦',exact:true}).click();
  let start=await point(1,2), end=await point(7,2);
  await pen('mousePressed',start); await pen('mouseMoved',end); await pen('mouseReleased',end);
  let cells=await grid(); assert.equal(cells.filter(x=>x===0).length,7);
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  assert.equal((await grid()).filter(x=>x===0).length,0);
  await page.getByRole('button',{name:'重做',exact:true}).click();
  assert.equal((await grid()).filter(x=>x===0).length,7);
  await page.getByTitle(`${palette.colors[0].code} (${palette.colors[0].hex})`,{exact:true}).click();
  start=await point(1,2); end=await point(7,2);
  await pen('mousePressed',start); await pen('mouseMoved',end); await pen('mouseReleased',end);
  assert.equal((await grid()).filter(x=>x===0).length,0);
  await page.getByRole('button',{name:'橡皮擦',exact:true}).click();
  start=await point(2,3); end=await point(6,3);
  await pen('mousePressed',start);
  const heldBox=await canvas.boundingBox();
  const palm=await point(4,5);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...palm,id:12}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:palm.x+25,y:palm.y+20,id:12}]});
  await pen('mouseMoved',end); await pen('mouseReleased',end);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:palm.x+40,y:palm.y+30,id:12}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.waitForTimeout(100);
  assert.equal((await canvas.boundingBox()).x,heldBox.x);
  assert.equal((await grid()).filter(x=>x===0).length,5);
  const before=await grid(); const box=await canvas.boundingBox();
  start=await point(4,4);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...start,id:11}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x+30,y:start.y+20,id:11}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.waitForTimeout(100);
  assert.deepEqual(await grid(),before);
  const moved=await canvas.boundingBox(); assert.ok(Math.abs(moved.x-box.x-30)<2); assert.ok(Math.abs(moved.y-box.y-20)<2);
  await page.reload();
  assert.deepEqual(await grid(),before);
  assert.deepEqual(errors,[]);
  console.log('PASS: color exclusion undo, hold-to-highlight, zoom/reset controls, readable fill prompt, pen fast paint/erase, whole stroke undo/redo, palm blocking, touch pan without edits, saved project reload; no page errors');
} finally { await browser.close(); }
